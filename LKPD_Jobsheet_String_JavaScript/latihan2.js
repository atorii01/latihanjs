// Soal 1: Escape \n untuk memisahkan baris
let alamat = 'Rumah saya beralamat di Jl. Merdeka No. 17,\nRT 03/RW 05.';
console.log(alamat);

// Soal 2: Path folder Windows menggunakan escape backslash (\\)
let pathFolder = "D:\\Tugas\\JavaScript\\latihan.js";
console.log(pathFolder);

// Soal 3: Kalimat dengan tanda kutip ganda menggunakan escape (\" )
let kutipan = "Ani berkata: \"Saya akan lulus tahun ini.\"";
console.log(kutipan);

